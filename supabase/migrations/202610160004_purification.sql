CREATE FUNCTION trigger_purification_reserve_reference() RETURNS trigger LANGUAGE plpgsql SET search_path=slowlax,pg_catalog AS $trigger$
BEGIN
IF NEW.event_type='reserve' AND NOT EXISTS(
 SELECT 1 FROM purification_credit_grants g JOIN purification_requests r ON r.user_id=g.user_id
 WHERE g.id=NEW.grant_id AND r.id=NEW.request_id AND r.status='submitted'
 AND julianday(g.starts_at)<=julianday('now') AND (g.expires_at IS NULL OR julianday(g.expires_at)>julianday('now'))
 AND NOT EXISTS(SELECT 1 FROM purification_credit_revocations v WHERE v.source_key=g.source_key)
 AND NEW.credits<=g.total_credits-COALESCE((SELECT SUM(CASE WHEN e.event_type='reserve' THEN e.credits ELSE -e.credits END) FROM purification_credit_events e WHERE e.grant_id=g.id),0)
 AND NEW.credits<=r.credits_used-COALESCE((SELECT SUM(e.credits) FROM purification_credit_events e WHERE e.request_id=r.id AND e.event_type='reserve'),0)) THEN
RAISE EXCEPTION 'Rening credits are unavailable' USING ERRCODE='23514'; 
END IF;
IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW; END;
$trigger$;
CREATE TRIGGER purification_reserve_reference BEFORE INSERT ON purification_credit_events FOR EACH ROW EXECUTE FUNCTION trigger_purification_reserve_reference();

