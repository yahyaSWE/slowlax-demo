/** Append-only diploma migration. The v1 baseline is deliberately untouched. */
import { writeFile } from "node:fs/promises";
import { COURSE_CERTIFICATES_SCHEMA } from "../src/lib/course-certificates-schema";

async function main() {
  const source = COURSE_CERTIFICATES_SCHEMA;
  const tableNames = [...source.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map(match => match[1]);
  const transform = (sql: string) => sql
    .replace(/\bIS NOT\s+((?:NEW|OLD)\.\w+)/gi, "IS DISTINCT FROM $1")
    .replace(/\bIS\s+((?:NEW|OLD)\.\w+)/gi, "IS NOT DISTINCT FROM $1");
  const tables = [...source.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)\s*\(([\s\S]*?)\);/g)]
    .map(match => transform(match[0]).replace("IF NOT EXISTS ", "")
      .replace(/(REFERENCES \w+\([^)]+\) ON DELETE (?:CASCADE|SET NULL))/g, "$1 DEFERRABLE INITIALLY IMMEDIATE"));
  const indexes = [...source.matchAll(/CREATE INDEX IF NOT EXISTS [\s\S]*?;/g)].map(match => match[0]);
  const triggers = [...source.matchAll(/CREATE TRIGGER IF NOT EXISTS (\w+)\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?: OF [\w,]+)?)\s+ON\s+(\w+)\s*(?:WHEN\s+([\s\S]*?))?\s*BEGIN\s+([\s\S]*?)END;/g)]
    .map(([, name, timing, event, table, condition, body]) => {
      const statements = transform(body).replace(/SELECT RAISE\(ABORT,'((?:[^']|'')*)'\);/g, "RAISE EXCEPTION '$1' USING ERRCODE='23514';");
      return `CREATE FUNCTION trigger_${name}() RETURNS trigger LANGUAGE plpgsql SET search_path=slowlax,pg_catalog AS $trigger$\nBEGIN\n${condition ? `  IF ${transform(condition)} THEN\n` : ""}${statements}${condition ? "\n  END IF;" : ""}\n  IF TG_OP='DELETE' THEN RETURN OLD; END IF;\n  RETURN NEW;\nEND;\n$trigger$;\nCREATE TRIGGER ${name} ${timing} ${event} ON ${table} FOR EACH ROW EXECUTE FUNCTION trigger_${name}();`;
    });
  const security = `${tableNames.map(table => `ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;`).join("\n")}
REVOKE ALL ON ALL TABLES IN SCHEMA slowlax FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA slowlax FROM PUBLIC;
DO $security$ DECLARE role_name TEXT; BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA slowlax FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA slowlax FROM %I',role_name);
    END IF;
  END LOOP;
END; $security$;`;
  const sql = ["-- Slowlax v2: optional, immutable course diplomas.", "SET LOCAL search_path=slowlax,pg_catalog;", ...tables, ...indexes, ...triggers, security,
    "UPDATE app_meta SET value='2' WHERE key='postgres_schema_version';"].join("\n\n")+"\n";
  await writeFile("supabase/migrations/202610150002_course_certificates.sql", "BEGIN;\nSELECT pg_advisory_xact_lock(1397509976,1);\n"+sql+"COMMIT;\n");
  await writeFile("src/lib/postgres-certificate-schema.ts", `// Generated by scripts/generate-postgres-certificate-schema.ts. Keep applied migrations immutable.\nimport { POSTGRES_BASELINE_SQL, POSTGRES_TABLES as BASELINE_TABLES } from "./postgres-schema";\nexport const POSTGRES_SCHEMA_VERSION = 2;\nexport const POSTGRES_TABLES = [...BASELINE_TABLES,...${JSON.stringify(tableNames)}] as const;\nexport const POSTGRES_CERTIFICATE_SQL = ${JSON.stringify(sql)};\nexport const POSTGRES_INITIAL_SCHEMA_SQL = POSTGRES_BASELINE_SQL+"\\n"+POSTGRES_CERTIFICATE_SQL;\n`);
  console.log(`Generated append-only PostgreSQL v2: ${tableNames.length} tables, ${triggers.length} integrity triggers.`);
}
main().catch(error => { console.error(error); process.exitCode=1; });
