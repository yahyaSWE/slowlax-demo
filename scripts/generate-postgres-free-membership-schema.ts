/** Append-only Bas migration. Previously versioned v1/v2 SQL stays frozen. */
import { writeFile } from "node:fs/promises";
import { FREE_MEMBERSHIP_SCHEMA } from "../src/lib/free-membership-schema";
import { COURSE_CERTIFICATE_INSERT_GUARD } from "../src/lib/course-certificates-schema";

async function main() {
  const source=FREE_MEMBERSHIP_SCHEMA;
  const names=[...source.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map(match=>match[1]);
  const tables=[...source.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)\s*\(([\s\S]*?)\);/g)]
    .map(match=>match[0].replace("IF NOT EXISTS ","").replace(/(REFERENCES \w+\([^)]+\) ON DELETE (?:CASCADE|SET NULL))/g,"$1 DEFERRABLE INITIALLY IMMEDIATE"));
  const initial=[...source.matchAll(/INSERT INTO (\w+)[^;]+;/g)].map(match=>match[0]);
  const triggers=[...source.matchAll(/CREATE TRIGGER IF NOT EXISTS (\w+)\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?: OF [\w,]+)?)\s+ON\s+(\w+)\s*(?:WHEN\s+([\s\S]*?))?\s*BEGIN\s+([\s\S]*?)END;/g)]
    .map(([,name,timing,event,table,condition,body])=>{
      const statements=body.replace(/SELECT RAISE\(ABORT,'((?:[^']|'')*)'\);/g,"RAISE EXCEPTION '$1' USING ERRCODE='23514';");
      return `CREATE FUNCTION trigger_${name}() RETURNS trigger LANGUAGE plpgsql SET search_path=slowlax,pg_catalog AS $trigger$\nBEGIN\n${condition?`  IF ${condition} THEN\n`:""}${statements}${condition?"\n  END IF;":""}\n  IF TG_OP='DELETE' THEN RETURN OLD; END IF;\n  RETURN NEW;\nEND;\n$trigger$;\nCREATE TRIGGER ${name} ${timing} ${event} ON ${table} FOR EACH ROW EXECUTE FUNCTION trigger_${name}();`;
    });
  const certificateGuard=`-- Extend the existing v2 guard without changing its historical migration.
CREATE OR REPLACE FUNCTION trigger_course_certificate_issuance_reference() RETURNS trigger LANGUAGE plpgsql SET search_path=slowlax,pg_catalog AS $trigger$
BEGIN
  IF NOT ${COURSE_CERTIFICATE_INSERT_GUARD} THEN
    RAISE EXCEPTION 'Certificate completion and ownership requirements failed' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$trigger$;`;
  const reserveBasSlug=`-- Reserve the free Bas URL without changing a single historical contract.
DO $reserve_bas$
DECLARE legacy_plan RECORD; base_slug TEXT; candidate TEXT; suffix INTEGER; revision TEXT;
BEGIN
  FOR legacy_plan IN SELECT id,updated_at FROM slowlax.membership_plans WHERE slug='bas' LOOP
    base_slug:='bas-betalt-'||legacy_plan.id::TEXT; candidate:=base_slug; suffix:=1;
    WHILE EXISTS(SELECT 1 FROM slowlax.membership_plans WHERE slug=candidate AND id<>legacy_plan.id) LOOP
      suffix:=suffix+1; candidate:=base_slug||'-'||suffix::TEXT;
    END LOOP;
    revision:=CASE WHEN slowlax.julianday(legacy_plan.updated_at)>=slowlax.julianday('now')
      THEN to_char((legacy_plan.updated_at::timestamptz+interval '1 millisecond') AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
      ELSE slowlax.iso_now() END;
    UPDATE slowlax.membership_plans SET slug=candidate,updated_at=revision WHERE id=legacy_plan.id;
  END LOOP;
END;
$reserve_bas$;`;
  const security=`${names.map(name=>`ALTER TABLE ${name} ENABLE ROW LEVEL SECURITY;`).join("\n")}
REVOKE ALL ON ALL TABLES IN SCHEMA slowlax FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA slowlax FROM PUBLIC;
DO $security$ DECLARE role_name TEXT; BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA slowlax FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA slowlax FROM %I',role_name);
    END IF;
  END LOOP;
END; $security$;`;
  const sql=["-- Slowlax v3: Bas free membership with live group access.","SET LOCAL search_path=slowlax,pg_catalog;",
    `DO $migration$ BEGIN IF (SELECT value FROM app_meta WHERE key='postgres_schema_version') IS DISTINCT FROM '2' THEN RAISE EXCEPTION 'Apply PostgreSQL v2 before v3'; END IF; END; $migration$;`,
    ...tables,...initial,...triggers,reserveBasSlug,certificateGuard,security,"UPDATE app_meta SET value='3' WHERE key='postgres_schema_version';"].join("\n\n")+"\n";
  await writeFile("supabase/migrations/202610160003_free_membership.sql","BEGIN;\nSELECT pg_advisory_xact_lock(1397509976,1);\n"+sql+"COMMIT;\n");
  await writeFile("src/lib/postgres-free-membership-schema.ts",`// Generated by scripts/generate-postgres-free-membership-schema.ts. Applied migrations stay immutable.\nimport { POSTGRES_INITIAL_SCHEMA_SQL as V2_INITIAL_SQL, POSTGRES_TABLES as V2_TABLES } from "./postgres-certificate-schema";\nexport const POSTGRES_SCHEMA_VERSION = 3;\nexport const POSTGRES_TABLES = [...V2_TABLES,...${JSON.stringify(names)}] as const;\nexport const POSTGRES_RESERVE_BAS_SLUG_SQL = ${JSON.stringify(reserveBasSlug)};\nexport const POSTGRES_FREE_MEMBERSHIP_SQL = ${JSON.stringify(sql)};\nexport const POSTGRES_INITIAL_SCHEMA_SQL = V2_INITIAL_SQL+"\\n"+POSTGRES_FREE_MEMBERSHIP_SQL;\n`);
  console.log(`Generated PostgreSQL v3: ${names.length} Bas tables and refreshed certificate access guard.`);
}
main().catch(error=>{console.error(error);process.exitCode=1;});
