/**
 * Generate the initial PostgreSQL baseline from the maintained SQLite models.
 * Run only while developing the baseline. Deployed changes require a new,
 * append-only PostgreSQL migration, never rewriting an applied migration.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { SCHEMA, ACCOUNT_EMAIL_SCHEMA, COURSE_ACTIVITY_SCHEMA, SLOT_SCHEDULE_SCHEMA } from "../src/lib/schema";
import { MEMBERSHIP_SCHEMA } from "../src/lib/membership-schema";
import { MEMBERSHIP_UPLOAD_SCHEMA } from "../src/lib/membership-upload-schema";
import { MEMBERSHIP_BILLING_SCHEMA } from "../src/lib/membership-billing-schema";
import { COURSE_PURCHASE_SCHEMA } from "../src/lib/course-purchase-schema";
import { COURSE_BUNDLES_SCHEMA } from "../src/lib/course-bundles-schema";
import { KIT_NEWSLETTER_SCHEMA } from "../src/lib/kit-newsletter-schema";

async function main() {
const excluded = new Set(["treatments", "availability_schedules", "availability_blocks", "slots", "bookings", "booking_email_outbox"]);
const sources = [SCHEMA, ACCOUNT_EMAIL_SCHEMA, COURSE_ACTIVITY_SCHEMA, SLOT_SCHEDULE_SCHEMA,
  MEMBERSHIP_SCHEMA, MEMBERSHIP_UPLOAD_SCHEMA, MEMBERSHIP_BILLING_SCHEMA, COURSE_PURCHASE_SCHEMA, COURSE_BUNDLES_SCHEMA, KIT_NEWSLETTER_SCHEMA];
const source = sources.join("\n");
const containsExcluded = (sql: string) => [...excluded].some(table => new RegExp(`\\b${table}\\b`, "i").test(sql));
const transform = (sql: string) => sql
  .replace(/\s+COLLATE NOCASE\b/gi, "")
  .replace(/strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)/g, "iso_now()")
  .replace(/\b(\w+) GLOB '([^']+)'/g, (_match, column, glob) => `${column} ~ '^${glob}$'`)
  .replace(/\bIS NOT\s+((?:NEW|OLD|a)\.\w+)/gi, "IS DISTINCT FROM $1")
  .replace(/\bIS\s+((?:NEW|OLD|a)\.\w+)/gi, "IS NOT DISTINCT FROM $1");

const tables = [...source.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)\s*\(([\s\S]*?)\);/g)]
  .filter(match => !excluded.has(match[1]));
const identities: string[] = [];
const tableStatements = tables.map(match => {
  let body = transform(match[2]);
  if (/\bid INTEGER PRIMARY KEY\b/.test(body)) {
    identities.push(match[1]);
    body = body.replace(/\bid INTEGER PRIMARY KEY\b/, "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
  }
  if (match[1] === "users") body += ", email_verified_at TEXT, supabase_id TEXT UNIQUE";
  // PostgreSQL requires referenced tables to exist. Add FKs separately after
  // every table exists (uploads and courses are intentionally mutually linked).
  const foreignKeys: string[] = [];
  body = body.replace(/\b(\w+) (INTEGER|TEXT)([^,]*?)\s+REFERENCES (\w+)\(([^)]+)\)( ON DELETE (?:CASCADE|SET NULL))?/g,
    (_all, column, type, definition, table, reference, action = "") => {
      foreignKeys.push(`ALTER TABLE ${match[1]} ADD FOREIGN KEY (${column}) REFERENCES ${table}(${reference})${action} DEFERRABLE INITIALLY IMMEDIATE;`);
      return `${column} ${type}${definition}`;
    });
  // Composite FKs are deferred too.
  body = body.replace(/,\s*FOREIGN KEY\(([^)]+)\) REFERENCES (\w+)\(([^)]+)\)( ON DELETE (?:CASCADE|SET NULL))?/g,
    (_all, columns, table, reference, action = "") => {
      foreignKeys.push(`ALTER TABLE ${match[1]} ADD FOREIGN KEY (${columns}) REFERENCES ${table}(${reference})${action} DEFERRABLE INITIALLY IMMEDIATE;`);
      return "";
    });
  return { sql: `CREATE TABLE ${match[1]} (${body});`, foreignKeys };
});
const indexes = [...source.matchAll(/CREATE (?:UNIQUE )?INDEX IF NOT EXISTS [\s\S]*?;/g)]
  .map(match => transform(match[0])).filter(sql => !containsExcluded(sql));
const initial = [...source.replace(/CREATE TRIGGER[\s\S]*?END;/g, "").matchAll(/INSERT(?: OR IGNORE)? INTO (\w+)[^;]+;/g)]
  .filter(match => !excluded.has(match[1])).map(match => transform(match[0]).replace("INSERT OR IGNORE", "INSERT").replace(/;$/, /ON CONFLICT/i.test(match[0]) ? ";" : " ON CONFLICT DO NOTHING;"));
const triggers = [...source.matchAll(/CREATE TRIGGER IF NOT EXISTS (\w+)\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?: OF [\w,]+)?)\s+ON\s+(\w+)\s*(?:WHEN\s+([\s\S]*?))?\s*BEGIN\s+([\s\S]*?)END;/g)]
  .filter(match => !containsExcluded(match[0])).map(match => {
    const [, name, timing, event, table, condition, body] = match;
    const statements = transform(body).replace(/SELECT RAISE\(ABORT,'((?:[^']|'')*)'\);/g, "RAISE EXCEPTION '$1' USING ERRCODE='23514';");
    return `CREATE FUNCTION trigger_${name}() RETURNS trigger LANGUAGE plpgsql SET search_path=slowlax,pg_catalog AS $trigger$\nBEGIN\n${condition ? `  IF ${transform(condition)} THEN\n` : ""}${statements}${condition ? "\n  END IF;" : ""}\n  IF TG_OP='DELETE' THEN RETURN OLD; END IF;\n  RETURN NEW;\nEND;\n$trigger$;\nCREATE TRIGGER ${name} ${timing} ${event} ON ${table} FOR EACH ROW EXECUTE FUNCTION trigger_${name}();`;
  });
const helpers = `CREATE SCHEMA IF NOT EXISTS slowlax;
REVOKE ALL ON SCHEMA slowlax FROM PUBLIC;
SET LOCAL search_path=slowlax,pg_catalog;
CREATE FUNCTION iso_now() RETURNS TEXT LANGUAGE sql STABLE AS $function$
  SELECT to_char(statement_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
$function$;
-- Match SQLite's invalid-date => NULL behavior rather than granting access
-- because invalid dates compare lexicographically as text.
CREATE FUNCTION julianday(value TEXT) RETURNS DOUBLE PRECISION LANGUAGE plpgsql STABLE AS $function$
BEGIN
  IF value IS NULL THEN RETURN NULL; END IF;
  IF value='now' THEN RETURN extract(epoch FROM statement_timestamp())/86400.0+2440587.5; END IF;
  IF value !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}([ T][0-9]{2}:[0-9]{2}(:[0-9]{2}(\\.[0-9]+)?)?(Z|[+-][0-9]{2}:[0-9]{2})?)?$' THEN RETURN NULL; END IF;
  RETURN extract(epoch FROM value::timestamptz)/86400.0+2440587.5;
EXCEPTION WHEN invalid_datetime_format OR datetime_field_overflow THEN RETURN NULL;
END;
$function$;
CREATE FUNCTION json_extract(value TEXT,path TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE STRICT AS $function$
  SELECT value::jsonb #>> string_to_array(substr(path,3),'.');
$function$;`;
const security = tables.map(match => `ALTER TABLE ${match[1]} ENABLE ROW LEVEL SECURITY;`).join("\n") + `
REVOKE ALL ON ALL TABLES IN SCHEMA slowlax FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA slowlax FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA slowlax FROM PUBLIC;
-- Supabase's browser roles have no route to application tables. The server
-- uses the private database owner connection; application authorization runs
-- in the server modules. Never expose SUPABASE_DB_URL to the browser.
DO $security$ DECLARE role_name TEXT; BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA slowlax FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA slowlax FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA slowlax FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA slowlax FROM %I',role_name);
    END IF;
  END LOOP;
END; $security$;`;
const sql = ["-- Slowlax PostgreSQL baseline. Booking and product-store tables are excluded.", helpers,
  ...tableStatements.map(table => table.sql), ...tableStatements.flatMap(table => table.foreignKeys),
  "CREATE UNIQUE INDEX users_email_lower ON users(lower(email));", ...indexes, ...initial, ...triggers,
  "UPDATE practitioners SET name='Slowlax',active=0 WHERE id=1;",
  "INSERT INTO app_meta(key,value) VALUES('postgres_schema_version','1');", security].join("\n\n") + "\n";
await mkdir("supabase/migrations", { recursive: true });
await writeFile("supabase/migrations/202610150001_slowlax.sql", "BEGIN;\nSELECT pg_advisory_xact_lock(1397509976,1);\n" + sql + "COMMIT;\n");
await writeFile("src/lib/postgres-schema.ts", `// Generated by scripts/generate-postgres-schema.ts. Keep applied migrations immutable.\nexport const POSTGRES_SCHEMA_VERSION = 1;\nexport const POSTGRES_TABLES = ${JSON.stringify(tables.map(table => table[1]))} as const;\nexport const POSTGRES_IDENTITY_TABLES = new Set(${JSON.stringify(identities)});\nexport const POSTGRES_BASELINE_SQL = ${JSON.stringify(sql)};\n`);
console.log(`Generated PostgreSQL baseline: ${tables.length} tables, ${triggers.length} integrity triggers.`);
}
main().catch(error => { console.error(error); process.exitCode=1; });
